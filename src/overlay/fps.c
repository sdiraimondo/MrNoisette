#include "overlay/fps.h"
#include <stdio.h>

static bool s_enabled = false;

void FPS_Toggle(void) { s_enabled = !s_enabled; }
bool FPS_IsEnabled(void) { return s_enabled; }
void FPS_SetEnabled(bool e) { s_enabled = e; }

static const uint8_t s_font[10][7] = {
  {0x0E,0x11,0x13,0x15,0x17,0x11,0x0E}, /* 0 */
  {0x04,0x0C,0x04,0x04,0x04,0x04,0x0E}, /* 1 */
  {0x0E,0x11,0x01,0x02,0x04,0x08,0x1F}, /* 2 */
  {0x1F,0x02,0x04,0x02,0x01,0x11,0x0E}, /* 3 */
  {0x02,0x06,0x0A,0x12,0x1F,0x02,0x02}, /* 4 */
  {0x1F,0x10,0x1E,0x01,0x01,0x11,0x0E}, /* 5 */
  {0x06,0x08,0x10,0x1E,0x11,0x11,0x0E}, /* 6 */
  {0x1F,0x01,0x02,0x04,0x08,0x08,0x08}, /* 7 */
  {0x0E,0x11,0x11,0x0E,0x11,0x11,0x0E}, /* 8 */
  {0x0E,0x11,0x11,0x0F,0x01,0x02,0x0C}, /* 9 */
};

static void RenderDigit(uint8 *dst, size_t pitch, int digit, int x0, int y0) {
  if (digit < 0 || digit > 9) return;
  for (int y = 0; y < 7; y++) {
    uint8 row = s_font[digit][y];
    for (int x = 0; x < 5; x++) {
      if (row & (0x10 >> x)) {
        uint8 *p = dst + (y0 + y) * pitch + (x0 + x) * 4;
        p[0] = 0xFF; p[1] = 0xFF; p[2] = 0xFF; p[3] = 0xFF;
      }
    }
  }
}

void FPS_Render(uint8 *pixels, size_t pitch, int fps) {
  if (!s_enabled) return;
  char buf[16];
  snprintf(buf, sizeof(buf), "%d", fps);
  int x = 4;
  for (int i = 0; buf[i]; i++) {
    if (buf[i] >= '0' && buf[i] <= '9')
      RenderDigit(pixels, pitch, buf[i] - '0', x, 4);
    x += 6;
  }
}
